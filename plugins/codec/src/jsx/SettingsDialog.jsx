const MODE_OPTIONS = [
  { label: 'base64', value: 'base64' },
  { label: 'base64url', value: 'base64url' },
  { label: 'url', value: 'url' },
  { label: 'hex', value: 'hex' },
  { label: 'unicode', value: 'unicode' },
  { label: 'html', value: 'html' },
  { label: 'jwt', value: 'jwt' },
  { label: 'query', value: 'query' },
  { label: 'dataurl', value: 'dataurl' },
]

export function SettingsDialog({ open, onClose, settings, onChange }) {
  const set = (key, value) => onChange(key, value)
  return (
    <Dialog open={open} onOpenChange={(next) => { if (!next) onClose() }}>
      <DialogContent className="pk-set-dialog">
        <DialogTitle>编解码设置</DialogTitle>
        <div className="pk-set">
          <div className="pk-set-row">
            <div className="pk-set-text">
              <span className="pk-set-label">默认工具</span>
            </div>
            <div className="pk-set-control">
              <Select
                ariaLabel="默认工具"
                value={settings.defaultMode ?? 'base64'}
                options={MODE_OPTIONS}
                onChange={(v) => set('defaultMode', v)}
              />
            </div>
          </div>
          <div className="pk-set-row">
            <div className="pk-set-text">
              <span className="pk-set-label">输入后自动转换</span>
            </div>
            <div className="pk-set-control">
              <Switch
                aria-label="输入后自动转换"
                checked={settings.liveConversion !== false}
                onCheckedChange={(v) => set('liveConversion', v)}
              />
            </div>
          </div>
          <div className="pk-set-row">
            <div className="pk-set-text">
              <span className="pk-set-label">严格校验 UTF-8</span>
            </div>
            <div className="pk-set-control">
              <Switch
                aria-label="严格校验 UTF-8"
                checked={settings.strictUtf8 !== false}
                onCheckedChange={(v) => set('strictUtf8', v)}
              />
            </div>
          </div>
        </div>
      </DialogContent>
    </Dialog>
  )
}
