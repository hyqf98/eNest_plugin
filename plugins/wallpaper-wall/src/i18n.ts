const dictionaries = { 'zh-CN': zhCN, 'en-US': enUS } as const
export type Locale = keyof typeof dictionaries
export type I18nKey = MessageKey

export function useI18n() {
  const [locale, setLocale] = useState<Locale>('zh-CN')

  useEffect(() => {
    const api = window.enest || window.zapi
    if (!api?.i18n) return
    let disposed = false
    void api.i18n.getLocale().then(next => {
      if (!disposed && (next === 'zh-CN' || next === 'en-US')) setLocale(next)
    }).catch(() => {})
    const off = api.i18n.onLocaleChange(event => {
      if (event.locale === 'zh-CN' || event.locale === 'en-US') setLocale(event.locale)
    })
    return () => {
      disposed = true
      off()
    }
  }, [])

  const t = useCallback((key: I18nKey, params?: Record<string, string | number>) => {
    const dictionary = dictionaries[locale] ?? zhCN
    let text: string = dictionary[key] ?? zhCN[key] ?? key
    if (params) {
      for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value))
    }
    return text
  }, [locale])

  return { locale, t }
}
