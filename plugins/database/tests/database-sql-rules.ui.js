import { test, expect } from '@playwright/test'
import { fixture, connect, navigate } from './database-fixture.js'

async function openSettings(page) {
  await fixture(page); await connect(page); await navigate(page, 'settings')
  await expect(page.getByRole('heading', { name: 'SQL 智能提示', exact: true })).toBeVisible()
}
const persisted = page => page.evaluate(() => window.__data['db.ui']?.completion)
async function save(page) {
  await page.locator('[data-save-completion]').click()
  await expect(page.locator('[data-save-state]')).toContainText('已保存')
}
async function applyJson(page, config) {
  await page.getByText('自定义函数、枚举和高级配置', { exact: true }).click()
  await page.locator('[data-completion-json]').fill(JSON.stringify(config))
  await page.locator('[data-apply-completion-json]').click()
  await expect(page.locator('[data-json-issues]')).toContainText('校验通过')
}
async function captureSection(page, selector, name) {
  await page.locator(selector).evaluate(element => element.scrollIntoView({ block: 'start', behavior: 'instant' }))
  await page.screenshot({ path: `test-results-db/${name}.png` })
}

test('custom functions are visually configured, scoped, previewed and restored', async ({ page }) => {
  await openSettings(page)
  const section = page.locator('[data-custom-functions]')
  await section.locator('[data-new-function]').click()
  await section.locator('[data-function-field=name]').fill('MASK_PHONE')
  await section.locator('[data-function-field=signature]').fill('MASK_PHONE(phone, keep_digits)')
  await section.locator('[data-function-field=description]').fill('手机号脱敏，保留指定尾号')
  await section.locator('.sql-rule-dialects summary').click()
  await section.locator('[data-function-dialect=mysql]').check()
  await save(page)
  await page.locator('[data-preview-sql]').fill('SELECT MASK_| FROM customers')
  await page.locator('[data-preview-run]').click()
  await expect(page.locator('[data-preview-results]')).toContainText('MASK_PHONE')
  await page.locator('[data-preview-dialect]').selectOption('postgres')
  await page.locator('[data-preview-run]').click()
  await expect(page.locator('[data-preview-results]')).not.toContainText('MASK_PHONE')
  await section.locator('.sql-rule-scope summary').click()
  await section.locator('[data-rule-scope=connectionId]').selectOption('dev')
  await save(page)
  const config = await persisted(page)
  expect(config.functions[0]).toMatchObject({ name: 'MASK_PHONE', signature: 'MASK_PHONE(phone, keep_digits)', dialects: ['mysql'], scope: { connectionId: 'dev' } })
  await captureSection(page, '[data-custom-functions]', 'database-sql-functions')
  await page.reload(); await navigate(page, 'settings')
  await expect(page.locator('[data-function-field=signature]')).toHaveValue('MASK_PHONE(phone, keep_digits)')
})

test('typed enum cells preserve types and reject incomplete numbers without losing input', async ({ page }) => {
  await openSettings(page)
  const section = page.locator('[data-static-enums]')
  await section.locator('[data-new-enum]').click()
  await section.locator('[data-enum-column]').fill('status')
  await section.locator('[data-rule-scope=table]').fill('customers')
  await section.locator('[data-rule-scope=connectionId]').selectOption('')
  await section.locator('[data-add-enum-value]').click()
  await section.locator('[data-enum-value="0"]').fill('001')
  await section.locator('[data-add-enum-value]').click()
  await section.locator('[data-enum-type="1"]').selectOption('number')
  await section.locator('[data-enum-value="1"]').fill('2.5')
  await section.locator('[data-add-enum-value]').click()
  await section.locator('[data-enum-type="2"]').selectOption('boolean')
  await section.locator('[data-enum-value="2"]').selectOption('false')
  await section.locator('[data-add-enum-value]').click()
  await section.locator('[data-enum-type="3"]').selectOption('null')
  await save(page)
  expect((await persisted(page)).enums[0].values).toEqual(['001', 2.5, false, null])
  await page.locator('[data-preview-sql]').fill('SELECT id FROM customers WHERE status = |')
  await page.locator('[data-preview-run]').click()
  await expect(page.locator('[data-preview-results]')).toContainText("'001'")
  await expect(page.locator('[data-preview-results]')).toContainText('FALSE')
  await section.locator('[data-enum-value="1"]').fill('1e')
  await page.locator('[data-save-completion]').click()
  await expect(page.locator('[data-save-state]')).toContainText('有限数值')
  await expect(section.locator('[data-enum-value="1"]')).toHaveValue('1e')
  expect((await persisted(page)).enums[0].values).toEqual(['001', 2.5, false, null])
  await section.locator('[data-enum-value="1"]').fill('1e3')
  await save(page)
  expect((await persisted(page)).enums[0].values).toEqual(['001', 1000, false, null])
  await captureSection(page, '[data-static-enums]', 'database-sql-enums')
})

test('visual scoped overrides inherit individually and preserve advanced JSON rules', async ({ page }) => {
  await openSettings(page)
  await applyJson(page, { profiles: [{ id: 'project', label: '项目规则', scope: { connectionId: 'dev', serverVersion: '8.0' }, overrides: { metadata: { prefetch: 'none' }, ranking: { pinned: ['field:customers:id'] }, behavior: { delayMs: 110 } } }] })
  const section = page.locator('[data-scoped-profiles]')
  await section.locator('[data-profile-label]').fill('订单库规则')
  await section.locator('[data-profile-override="behavior.automatic"]').check()
  await section.locator('[data-profile-value="behavior.automatic"]').selectOption('false')
  await section.locator('[data-profile-override="diagnostics.selectStar"]').check()
  await section.locator('[data-profile-value="diagnostics.selectStar"]').selectOption('off')
  await save(page)
  const first = (await persisted(page)).profiles[0]
  expect(first.scope).toEqual({ connectionId: 'dev', serverVersion: '8.0' })
  expect(first.overrides).toMatchObject({ metadata: { prefetch: 'none' }, ranking: { pinned: ['field:customers:id'] }, behavior: { delayMs: 110, automatic: false }, diagnostics: { selectStar: 'off' } })
  await section.locator('[data-profile-override="behavior.delayMs"]').uncheck()
  await expect(section.locator('[data-profile-value="behavior.delayMs"]')).toBeDisabled()
  await expect(section.locator('[data-profile-value="behavior.delayMs"]')).toHaveValue('70')
  await section.locator('[data-profile-override="behavior.delayMs"]').check()
  await section.locator('[data-profile-value="behavior.delayMs"]').fill('')
  await page.locator('[data-save-completion]').click()
  await expect(page.locator('[data-save-state]')).toContainText('0–2000')
  await section.locator('[data-profile-override="behavior.delayMs"]').uncheck()
  await save(page)
  expect((await persisted(page)).profiles[0].overrides.behavior).toEqual({ automatic: false })
  await captureSection(page, '[data-scoped-profiles]', 'database-sql-profile-settings')
  await page.setViewportSize({ width: 720, height: 700 })
  await section.scrollIntoViewIfNeeded()
  expect(await section.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: 'test-results-db/database-sql-visual-rules.png' })
})

test('dynamic template controls edit INSERT, UPDATE, fixed field groups and SELECT aliases', async ({ page }) => {
  await openSettings(page)
  await applyJson(page, {
    columnSets: [{ id: 'common', label: '客户常用字段', scope: { table: 'customers' }, columns: ['name', 'status'] }],
    templates: [{ id: 'write', label: '新增客户', trigger: 'ins', generator: 'insert', contexts: ['statementStart'], projection: { source: 'columnSet', columnSetId: 'common', choose: true }, table: { source: 'picker' } }]
  })
  const section = page.locator('[data-query-templates]')
  await section.locator('[data-select-template=write]').click()
  await expect(section.locator('[data-template-field=generator]')).toHaveValue('insert')
  await expect(section.locator('[data-template-column-set]')).toHaveValue('common')
  await section.locator('[data-template-field=label]').fill('新增客户字段')
  await save(page)
  expect((await persisted(page)).templates.find(item => item.id === 'write')).toMatchObject({ label: '新增客户字段', generator: 'insert', projection: { source: 'columnSet', columnSetId: 'common', choose: true }, table: { source: 'picker' } })
  await page.locator('[data-preview-sql]').fill('ins customers|')
  await page.locator('[data-preview-run]').click()
  await page.locator('[data-preview-item]').filter({ hasText: 'ins · customers' }).click()
  await expect(page.locator('[data-edit-preview]')).toContainText('INSERT INTO customers (name, status)')
  await section.locator('[data-template-field=generator]').selectOption('update')
  await section.locator('[data-template-field=trigger]').fill('upd')
  await page.locator('[data-preview-sql]').fill('upd customers|')
  await page.locator('[data-preview-run]').click()
  await page.locator('[data-preview-item]').filter({ hasText: 'upd · customers' }).click()
  await expect(page.locator('[data-edit-preview]')).toContainText('UPDATE customers')
  await expect(page.locator('[data-edit-preview]')).toContainText('WHERE')
  await section.locator('[data-template-field=generator]').selectOption('select')
  await section.locator('[data-template-field=trigger]').fill('short')
  await section.locator('[data-template-alias]').selectOption('initials')
  await section.locator('[data-template-limit]').fill('45')
  await save(page)
  await page.locator('[data-preview-sql]').fill('short customers|')
  await page.locator('[data-preview-run]').click()
  await page.locator('[data-preview-item]').filter({ hasText: 'short · customers' }).click()
  await expect(page.locator('[data-edit-preview]')).toContainText('SELECT c.name, c.status')
  await expect(page.locator('[data-edit-preview]')).toContainText('LIMIT 45')
  expect((await persisted(page)).templates.find(item => item.id === 'write').projection.choose).toBe(true)
  await captureSection(page, '[data-query-templates]', 'database-sql-template-settings')
  // Switching generators removes an invalid SELECT-only draft, while the
  // last valid limit survives for a future switch back to SELECT.
  await section.locator('[data-template-limit]').fill('')
  await page.locator('[data-save-completion]').click()
  await expect(page.locator('[data-save-state]')).toContainText('1–10000')
  await section.locator('[data-template-field=generator]').selectOption('snippet')
  await section.locator('[data-template-body]').fill('SELECT ${1:id} FROM customers;')
  await save(page)
  expect((await persisted(page)).templates.find(item => item.id === 'write')).toMatchObject({ generator: 'snippet', body: 'SELECT ${1:id} FROM customers;', limit: { value: 45 } })
})

test('snippet contexts are selectable and text is saved immediately without a blur', async ({ page }) => {
  await openSettings(page)
  const section = page.locator('[data-query-templates]')
  await section.locator('[data-new-template]').click()
  await section.locator('[data-template-field=trigger]').fill('activeonly')
  await section.locator('[data-template-body]').fill("status = 'active'")
  await section.locator('summary').filter({ hasText: '建议位置' }).click()
  await section.locator('[data-template-context=statementStart]').uncheck()
  await section.locator('[data-template-context=where]').check()
  await save(page)
  const template = (await persisted(page)).templates.find(item => item.trigger === 'activeonly')
  expect(template.contexts).toEqual(['where'])
  expect(template.body).toBe("status = 'active'")
  await page.locator('[data-preview-sql]').fill('SELECT id FROM customers WHERE activeo|')
  await page.locator('[data-preview-run]').click()
  await expect(page.locator('[data-preview-results]')).toContainText('activeonly')
  await page.locator('[data-preview-sql]').fill('activeo|')
  await page.locator('[data-preview-run]').click()
  await expect(page.locator('[data-preview-results]')).toContainText('当前没有匹配')
})
