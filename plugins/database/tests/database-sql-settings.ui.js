import { test, expect } from '@playwright/test'
import { fixture, connect, navigate } from './database-fixture.js'

async function openSettings(page) {
  await fixture(page); await connect(page); await navigate(page, 'settings')
  await expect(page.getByRole('heading', { name: 'SQL 智能提示', exact: true })).toBeVisible()
}
const persisted = page => page.evaluate(() => window.__data['db.ui']?.completion)

test('completion behavior persists and failed saves retain the edited draft', async ({ page }) => {
  await openSettings(page)
  await page.locator('[data-config="behavior.delayMs"]').fill('120')
  await page.locator('[data-config="behavior.keywordCase"]').selectOption('lower')
  await page.locator('[data-config="behavior.acceptOnEnter"]').check()
  await page.locator('[data-save-completion]').click()
  await expect(page.locator('[data-save-state]')).toContainText('已保存')
  expect((await persisted(page)).behavior).toMatchObject({ delayMs: 120, keywordCase: 'lower', acceptOnEnter: true })
  await page.locator('[data-config="behavior.delayMs"]').fill('230')
  await page.evaluate(() => window.__storageFail = true)
  await page.locator('[data-save-completion]').click()
  await expect(page.locator('[data-save-state]')).toContainText('草稿仍保留')
  await expect(page.locator('[data-config="behavior.delayMs"]')).toHaveValue('230')
  expect((await persisted(page)).behavior.delayMs).toBe(120)
  await page.evaluate(() => window.__storageFail = false)
  await page.locator('[data-save-completion]').click()
  await expect(page.locator('[data-save-state]')).toContainText('已保存')
  await page.reload(); await navigate(page, 'settings')
  await expect(page.locator('[data-config="behavior.delayMs"]')).toHaveValue('230')
})

test('visual field groups preserve order and copied templates remain editable', async ({ page }) => {
  await openSettings(page)
  await page.locator('[data-new-set]').click()
  await page.locator('[data-set-field=label]').fill('客户列表')
  await page.locator('[data-set-scope=table]').fill('customers')
  await page.locator('[data-manual-columns]').fill('id, name, status')
  await page.locator('[data-manual-columns]').press('Tab')
  await page.locator('[data-move-column="2:-1"]').click()
  await expect(page.locator('[data-manual-columns]')).toHaveValue('id, status, name')
  await page.locator('[data-copy-template]').click()
  await page.locator('[data-template-field=label]').fill('带条件查询')
  await page.locator('[data-template-field=trigger]').fill('selwhere')
  await page.locator('[data-template-field=generator]').selectOption('snippet')
  await page.locator('[data-template-body]').fill('SELECT ${1:id} FROM ${2:customers} WHERE ${3:id = 1}; $0')
  await page.locator('[data-save-completion]').click()
  await expect(page.locator('[data-save-state]')).toContainText('已保存')
  const config = await persisted(page)
  expect(config.columnSets.find(item => item.label === '客户列表').columns).toEqual(['id', 'status', 'name'])
  expect(config.templates.find(item => item.trigger === 'selwhere').body).toContain('${2:customers}')
  expect(config.templates.find(item => item.id === 'builtin.select-all').generator).toBe('select')
})

test('imports validate before merge and require explicit mapping of foreign connection IDs', async ({ page }) => {
  await openSettings(page)
  await page.getByText('自定义函数、枚举和高级配置', { exact: true }).click()
  await page.locator('[data-completion-json]').fill('{"schemaVersion":99}')
  await page.locator('[data-apply-completion-json]').click()
  await expect(page.locator('[data-json-issues]')).toContainText('schemaVersion')
  await page.locator('[data-reset-completion]').click()
  await page.getByText('自定义函数、枚举和高级配置', { exact: true }).click()
  const imported = { schemaVersion: 1, columnSets: [{ id: 'import.customers', label: '迁移客户字段', scope: { connectionId: 'foreign-machine', table: 'customers' }, columns: ['id', 'name'], order: 'configured' }] }
  await page.locator('[data-import-file]').setInputFiles({ name: 'completion.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(imported)) })
  await expect(page.locator('[data-import-preview]')).toBeVisible()
  await page.locator('[data-apply-import]').click()
  await expect(page.locator('[data-json-issues]')).toContainText('未映射')
  await page.locator('[data-map-connection="foreign-machine"]').selectOption('dev')
  await page.locator('[data-apply-import]').click()
  await page.locator('[data-save-completion]').click()
  await expect(page.locator('[data-save-state]')).toContainText('已保存')
  expect((await persisted(page)).columnSets.find(item => item.id === 'import.customers').scope.connectionId).toBe('dev')
})

test('playground offers field candidates and never executes SQL; responsive settings remain bounded', async ({ page }) => {
  await openSettings(page)
  const executions = () => page.evaluate(() => window.__calls.filter(call => call[0] === 'execute').length)
  const before = await executions()
  await page.locator('[data-preview-sql]').fill('SELECT c.| FROM customers c')
  await page.locator('[data-preview-run]').click()
  await expect(page.locator('[data-preview-results]')).toContainText('mobile')
  await page.locator('[data-preview-item]').first().click()
  await expect(page.locator('[data-edit-preview]')).toBeVisible()
  expect(await executions()).toBe(before)
  await page.setViewportSize({ width: 1024, height: 800 })
  await page.locator('[data-completion-playground]').scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results-db/database-sql-settings-preview.png' })
  await page.setViewportSize({ width: 720, height: 700 })
  expect(await page.locator('.sql-completion-settings').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
})
