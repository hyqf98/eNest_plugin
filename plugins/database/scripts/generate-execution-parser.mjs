#!/usr/bin/env node
/** Generate the editor grammar from the plugin backend's pure SQL parser. */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const input = new URL('../backend/sqlScript.ts', import.meta.url)
const output = new URL('../src/js/executionParser.js', import.meta.url)

export function generateExecutionParser({ check = false } = {}) {
  const compiled = ts.transpileModule(readFileSync(input, 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: false }
  }).outputText
  const content = `/** Generated by scripts/generate-execution-parser.mjs from backend/sqlScript.ts. Do not edit. */\n${compiled}`
  const current = existsSync(output) ? readFileSync(output, 'utf8') : undefined
  if (check && current !== content) throw new Error('Database execution parser is out of date; run npm run parser:generate in the database plugin')
  if (!check && current !== content) writeFileSync(output, content)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2)
  if (args.some(arg => arg !== '--check')) throw new Error('Usage: node scripts/generate-execution-parser.mjs [--check]')
  const check = args.includes('--check')
  generateExecutionParser({ check })
  console.log(check ? 'Database execution parser matches the plugin backend source' : 'Generated database execution parser')
}
