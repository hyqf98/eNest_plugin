#!/usr/bin/env node
/** Keep editor execution boundaries identical to the host without a runtime repo dependency. */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const hostFlag = process.argv.indexOf('--host-root')
const host = resolve(hostFlag < 0 ? join(repository, '..') : process.argv[hostFlag + 1])
let ts
try { ts = createRequire(join(repository, 'package.json'))('typescript') }
catch { ts = createRequire(join(host, 'package.json'))('typescript') }
const input = join(host, 'src/main/database/sqlScript.ts')
const output = join(repository, 'plugins/database/src/js/executionParser.js')
const compiled = ts.transpileModule(readFileSync(input, 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: false }
}).outputText
const content = `/** Generated by scripts/generate-db-execution-parser.mjs from host sqlScript.ts. Do not edit. */\n${compiled}`
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== content) throw new Error('Database execution parser is out of date; regenerate it from the host')
  console.log('Database execution parser matches the host')
} else { writeFileSync(output, content); console.log('Generated database execution parser') }
