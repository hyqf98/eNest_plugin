test('restored tabs preserve navigation and drafts without reopening database connections', async ({ page }) => {
  await fixture(page); await connect(page); await setQuery(page, 'SELECT restored_draft;')
  const firstId = await activeId(page)
  await connect(page, 'analytics'); await setQuery(page, 'SELECT restored_analytics;')
  const secondId = await activeId(page)
  await page.evaluate(() => window.__beforeClose())
  await page.reload()
  await expect(tabButton(page, firstId)).toBeVisible(); await expect(tabButton(page, secondId)).toBeVisible()
  expect(await activeId(page)).toBe(secondId)
  await expect(page.locator('#editor-host textarea')).toHaveValue('SELECT restored_analytics;')
  expect(await page.evaluate(() => window.__calls.filter(call => ['open', 'execute', 'table.page'].includes(call[0])))).toEqual([])
  await tabButton(page, firstId).click()
  await expect(page.locator('#editor-host textarea')).toHaveValue('SELECT restored_draft;')
  expect(await page.evaluate(() => window.__calls.some(call => call[0] === 'open'))).toBe(false)
})

test('tree metadata uses a separate read-only session and opening an object reuses its tab', async ({ page }) => {
  await fixture(page); await openNavigation(page)
  await page.locator('[data-expand-connection=dev]').click()
  await expect(page.locator('.nav-connections [data-object=orders]')).toBeVisible()
  const metadata = await page.evaluate(() => window.__calls.find(call => call[0] === 'open')[1])
  expect(metadata.sessionKey).toMatch(/^db-nav:/)
  expect(metadata.config.readOnly).toBe(true)
  expect(metadata.config.options.readOnly).toBe(true)
  await connect(page)
  const query = await page.evaluate(() => window.__calls.filter(call => call[0] === 'open').find(call => !call[1].sessionKey.startsWith('db-nav:'))[1])
  expect(query.sessionKey).not.toBe(metadata.sessionKey)
  expect(query.config.readOnly).toBe(false)
  await openObject(page, 'data')
  const objectId = await activeId(page), count = await page.locator('#workspace-tabs [role=tab]').count()
  await openObject(page, 'structure')
  expect(await activeId(page)).toBe(objectId)
  expect(await page.locator('#workspace-tabs [role=tab]').count()).toBe(count)
  await expect(page.getByRole('heading', { name: '关系图' })).toBeVisible()
  await openObject(page, 'data')
  const reads = await page.evaluate(() => window.__calls.filter(call => call[0] === 'table.page').length)
  await openObject(page, 'data')
  expect(await activeId(page)).toBe(objectId)
  expect(await page.evaluate(() => window.__calls.filter(call => call[0] === 'table.page').length)).toBe(reads)
  await page.locator('[data-object-refresh]').click()
  await expect.poll(() => page.evaluate(() => window.__calls.filter(call => call[0] === 'table.page').length)).toBe(reads + 1)
})

test('delayed completion discovery never blocks query execution or a new object read', async ({ page }) => {
  await fixture(page)
  await page.evaluate(() => { window.__strictSessionTasks = true; window.__deferCatalog = true })
  await connect(page); await setQuery(page, 'SELECT id, name FROM customers;')
  await expect.poll(() => page.evaluate(() => window.__pendingCatalog.length)).toBe(1)
  const metadataKey = await page.evaluate(() => window.__pendingCatalog[0].request.sessionKey)
  expect(metadataKey).toMatch(/^db-nav:catalog:/)
  const metadata = await page.evaluate(key => window.__sessions[key], metadataKey)
  expect(metadata.readOnly).toBe(true)
  expect(metadata.options.readOnly).toBe(true)
  await runQuery(page)
  await expect(page.locator('.grid-viewport')).toContainText('阿尔法')
  await openObject(page, 'data')
  await expect(page.locator('.grid-viewport')).toContainText('阿尔法')
  expect(await page.evaluate(() => window.__pendingCatalog.length)).toBe(1)
  await page.evaluate(() => { window.__deferCatalog = false; window.__pendingCatalog.shift().finish() })
  await expect.poll(() => page.evaluate(key => window.__busySessions.has(key), metadataKey)).toBe(false)
  const calls = await page.evaluate(() => window.__calls)
  expect(calls.filter(call => call[0] === 'busy-rejected')).toEqual([])
  expect(calls.filter(call => ['execute', 'table.page'].includes(call[0])).every(call => call[1].sessionKey !== metadataKey)).toBe(true)
  // Metadata sessions are reused until invalidation/disposal; only referenced columns may load.
  expect(calls.filter(call => call[0] === 'schema.describe' && call[1].sessionKey === metadataKey).every(call => call[1].table === 'customers')).toBe(true)
  await page.evaluate(() => window.__beforeClose())
  await expect.poll(() => page.evaluate(key => window.__calls.some(call => call[0] === 'close' && call[1] === key), metadataKey)).toBe(true)
})

