test('CSV import requires a current preview and Escape restores the invoking control', async ({ page }) => {
  await fixture(page); await connect(page); await setQuery(page, 'SELECT id, name FROM customers;')
  await runQuery(page)
  const openImport = async () => {
    await page.locator('#top-more').click()
    await page.locator('.ctx-menu [data-k=import]').click()
    await expect(page.getByRole('dialog', { name: 'CSV 导入' })).toBeVisible()
  }
  await openImport()
  await page.keyboard.press('Escape')
  await expect(page.locator('dialog')).toHaveCount(0)
  await expect(page.locator('#top-more')).toBeFocused()
  await openImport()
  const dialog = page.getByRole('dialog', { name: 'CSV 导入' })
  const run = dialog.locator('[data-act=run]')
  await dialog.locator('[data-el=table]').fill('customers')
  await dialog.locator('[data-el=csv]').fill('id,name\n3,Gamma')
  await expect(run).toBeDisabled()
  await dialog.locator('[data-act=preview]').click()
  await expect(dialog.locator('[data-el=preview]')).toContainText('3 | Gamma')
  await expect(run).toBeEnabled()
  await dialog.locator('[data-el=csv]').fill('id,name\n4,Delta')
  await expect(run).toBeDisabled()
  await expect(dialog.locator('[data-el=hint]')).toContainText('请重新预览')
  expect(await page.evaluate(() => window.__calls.some(call => call[0] === 'importRun'))).toBe(false)
  await dialog.locator('[data-act=preview]').click()
  await expect(run).toBeEnabled()
  await dialog.locator('[data-el=upsert]').check()
  await expect(run).toBeDisabled()
  await dialog.locator('[data-act=preview]').click()
  await expect(run).toBeEnabled()
  await run.click()
  await expect(dialog).toHaveCount(0)
  const request = await page.evaluate(() => window.__calls.find(call => call[0] === 'importRun')[1])
  expect(request).toMatchObject({ table: { table: 'customers' }, csvText: 'id,name\n4,Delta', options: { delimiter: ',', hasHeader: true, conflict: 'upsert' }, confirmed: true })
  const source = await page.evaluate(() => window.__calls.find(call => call[0] === 'execute')[1].sessionKey)
  expect(request.sessionKey).toBe(source)
})

test('the workbench stays usable across desktop and Quick sizes, themes and reduced motion', async ({ page }) => {
  await fixture(page); await connect(page); await setQuery(page, 'SELECT id, name FROM customers;')
  await runQuery(page); await expect(page.locator('.grid-viewport')).toContainText('阿尔法')
  for (const [width, height, theme, motion] of [[1280, 800, 'light', 'high'], [960, 640, 'dark', 'low'], [720, 420, 'light', 'medium']]) {
    await page.setViewportSize({ width, height })
    await page.evaluate(({ theme, motion }) => { document.documentElement.dataset.theme = theme; document.documentElement.dataset.anim = motion }, { theme, motion })
    await expect(page.locator('.wb-status')).toBeInViewport({ ratio: 1 })
    await expect(page.locator('#workspace-tabs')).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
    await page.screenshot({ path: `test-results-db/database-workspace-${width}-${theme}.png` })
  }
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.evaluate(() => { window.__manyRows = 200; document.documentElement.style.setProperty('--font-size-base', '16.9px') })
  await runQuery(page)
  const metric = page.locator('[data-el=rowMetric]')
  await expect.poll(() => metric.evaluate(element => element.getBoundingClientRect().height)).toBeGreaterThan(36)
  const rowHeight = await metric.evaluate(element => element.getBoundingClientRect().height)
  const viewport = page.locator('.grid-viewport')
  await viewport.evaluate((element, rowHeight) => { element.scrollTop = rowHeight * 35 }, rowHeight)
  await expect(viewport.locator('[data-row="35"]')).toBeVisible()
  const dimensions = await page.locator('.grid-canvas').evaluate(element => ({ canvas: element.getBoundingClientRect().height, row: element.querySelector('.tr').getBoundingClientRect().height, first: Number(element.querySelector('.tr').dataset.row) }))
  expect(Math.abs(dimensions.row - rowHeight)).toBeLessThan(0.1)
  expect(Math.abs(dimensions.canvas - rowHeight * 200)).toBeLessThan(0.1)
  expect(dimensions.first).toBeGreaterThan(20)
  await expect(viewport.locator('[data-r="35"][data-c="1"]')).toHaveText('item-36')
  await page.screenshot({ path: 'test-results-db/database-workspace-font-130.png' })
  await page.evaluate(() => document.documentElement.style.removeProperty('--font-size-base'))
  await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'dark' })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; window.__mode('quick') }); await page.setViewportSize({ width: 480, height: 240 })
  await openNavigation(page)
  await expect(page.locator('.nav-search')).toBeInViewport({ ratio: 1 })
  await page.screenshot({ path: 'test-results-db/database-quick-connections-dark.png' })
  await page.keyboard.press('Escape')
  await expect(page.locator('.wb-status')).toBeInViewport({ ratio: 1 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
})
