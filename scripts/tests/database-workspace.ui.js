  await page.evaluate(() => window.__finishBatch())
  await expect.poll(() => page.evaluate(() => window.__toasts.some(item => item.message?.includes('提交完成')))).toBe(true)
  expect(await activeId(page)).toBe(visibleId)
  await expect(page.locator('#results')).not.toContainText('后台提交的名字')
  await tabButton(page, sourceId).click()
  await expect(page.locator('.grid-viewport [data-r="0"][data-c="1"]')).toHaveText('后台提交的名字')
  await expect(page.locator('.grid-viewport .row-dirty')).toHaveCount(0)
