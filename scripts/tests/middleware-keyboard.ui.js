import { test, expect } from '@playwright/test'
import { fixture, openConnection, openPage } from './middleware-fixture.js'

test('Chinese IME confirmation cannot send or reformat a payload; deliberate execution keeps Unicode', async ({ page }) => {
  await fixture(page); await openConnection(page)
  const publish = await openPage(page, 'publish'), editor = publish.getByLabel('消息内容')
  await publish.getByLabel('发布目标').fill('order-events')
  await editor.fill('{"消息":"订单已完成 ✅；下一步"}')
  await editor.dispatchEvent('compositionstart', { data: '中文' })
  await editor.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true, metaKey: true, ctrlKey: true })
  await editor.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', keyCode: 229, metaKey: true, ctrlKey: true })
  expect(await page.evaluate(() => window.__mwCalls.filter(call => call.action === 'messages.send'))).toEqual([])
  await editor.dispatchEvent('compositionend', { data: '中文' })
  await editor.press('Alt+Shift+F')
  await expect(editor).toHaveValue('{\n  "消息": "订单已完成 ✅；下一步"\n}')
  await editor.press('Meta+a'); await editor.press('Meta+Enter')
  await expect.poll(() => page.evaluate(() => window.__mwCalls.filter(call => call.action === 'messages.send').length)).toBe(1)
  const sent = await page.evaluate(() => window.__mwCalls.find(call => call.action === 'messages.send').input.payload)
  expect(sent).toBe('{\n  "消息": "订单已完成 ✅；下一步"\n}')
  expect(sent).not.toContain('\uFFFD')
  await expect(editor).toHaveValue(sent)
})

test('repeated query shortcuts and an emptied target cannot strand a pending query in loading state', async ({ page }) => {
  await fixture(page); await openConnection(page)
  const messages = await openPage(page, 'messages'), target = messages.getByLabel('消息查询目标')
  const button = messages.getByRole('button', { name: '查询', exact: true }), state = messages.locator('.request-status')
  const queryCalls = () => page.evaluate(() => window.__mwCalls.filter(call => call.action === 'messages.query'))
  await target.fill('order-events'); await target.press('Control+Enter')
  await expect(messages.locator('tbody')).toContainText('23942')
  await page.evaluate(() => { window.__deferQuery = true })
  await target.press('Control+Enter')
  await expect(button).toBeDisabled()
  await expect.poll(() => page.evaluate(() => typeof window.__resolveQuery)).toBe('function')
  await target.press('Control+Enter')
  await target.fill(''); await target.press('Control+Enter')
  expect((await queryCalls()).length).toBe(2)
  await expect(state).toContainText('正在读取 order-events')
  await expect(messages.locator('tbody')).toContainText('23942')
  await page.evaluate(() => window.__resolveQuery())
  await expect(state).toContainText('order-events · 已读取 1 条')
  await expect(button).toBeEnabled()
  await expect(messages.locator('.loading-bar')).toBeHidden()
  await expect(target).toHaveValue('')
  await target.press('Control+Enter')
  expect((await queryCalls()).length).toBe(2)
  await expect(button).toBeEnabled()
  await page.evaluate(() => { window.__deferQuery = false })
  await target.fill('payment-events'); await target.press('Control+Enter')
  await expect(state).toContainText('payment-events · 已读取 1 条')
  const requests = await queryCalls()
  expect(requests.length).toBe(3)
  expect(requests.at(-1).input.topic).toBe('payment-events')
  expect(requests.at(-1).input.sessionKey).toBe('mw:orders')
  await expect(messages.locator('tbody td').last()).toHaveAttribute('title', /"status":"created"/)
})
